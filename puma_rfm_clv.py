# ADDITIONAL EVALUATION 3: ROLLING-WINDOW BACKTEST (3 folds)
# ═════════════════════════════════════════════════════════════
# A single 30-day train/test split may be unrepresentative if
# December is atypically slow. Rolling-window backtesting trains
# on an expanding window and tests on 3 different 30-day periods
# (Jul, Oct, Jan-2026) to give season-robust MAE/RMSE estimates.
#
#  Fold 1: Train Jan–Jun 2025  → Test Jul  2025 (summer peak)
#  Fold 2: Train Jan–Sep 2025  → Test Oct  2025 (post-peak)
#  Fold 3: Train Jan–Nov 2025  → Test Dec  2025 (holiday)
# ═════════════════════════════════════════════════════════════

print("\n── Additional Evaluation 3: Rolling-Window Backtest ────────────")

HORIZON = 30
folds   = [
    ("Fold 1 (Jul)", 181,          181+HORIZON),
    ("Fold 2 (Oct)", 273,          273+HORIZON),
    ("Fold 3 (Dec)", len(daily_sales)-HORIZON, len(daily_sales)),
]

roll_results = {'SARIMA':[], 'Prophet':[], 'XGBoost':[]}

for fold_name, train_end_idx, test_end_idx in folds:
    if test_end_idx > len(daily_sales):
        test_end_idx = len(daily_sales)

    tr = daily_sales.iloc[:train_end_idx].copy()
    te = daily_sales.iloc[train_end_idx:test_end_idx].copy()

    if len(te) == 0:
        continue

    y_tr_f = tr['y'].values
    y_te_f = te['y'].values

    # ── SARIMA fold ──────────────────────────────────────────
    try:
        am = auto_arima(y_tr_f, seasonal=True, m=7, d=None, D=None,
                        max_p=3, max_q=3, max_P=2, max_Q=2,
                        information_criterion='aic', stepwise=True,
                        suppress_warnings=True, error_action='ignore')
        sm = SARIMAX(y_tr_f, order=am.order, seasonal_order=am.seasonal_order,
                     enforce_stationarity=False, enforce_invertibility=False)
        sf = sm.fit(disp=False)
        sp = sf.get_forecast(steps=len(y_te_f)).predicted_mean
        roll_results['SARIMA'].append(mean_absolute_error(y_te_f, sp[:len(y_te_f)]))
    except Exception as e:
        print(f"  SARIMA {fold_name} failed: {e}")

    # ── Prophet fold ─────────────────────────────────────────
    try:
        pm = Prophet(yearly_seasonality=True, weekly_seasonality=True,
                     daily_seasonality=False, changepoint_prior_scale=0.05,
                     interval_width=0.95)
        pm.fit(tr[['ds','y']])
        fut = pm.make_future_dataframe(periods=len(y_te_f))
        pfc = pm.predict(fut)
        pp  = pfc.tail(len(y_te_f))['yhat'].values
        roll_results['Prophet'].append(mean_absolute_error(y_te_f, pp))
    except Exception as e:
        print(f"  Prophet {fold_name} failed: {e}")

    # ── XGBoost fold ─────────────────────────────────────────
    try:
        lag_tr  = build_lag_features(tr)
        lag_all = build_lag_features(daily_sales.iloc[:test_end_idx])
        lag_st  = len(daily_sales.iloc[:test_end_idx]) - len(lag_all)
        fc_ts   = [c for c in lag_tr.columns if c not in ['ds','y']]
        X_tr_f  = lag_tr[fc_ts]
        y_tr_f2 = lag_tr['y']
        te_idx  = train_end_idx - lag_st
        X_te_f  = lag_all[fc_ts].iloc[te_idx:te_idx+len(y_te_f)]
        xm = XGBRegressor(n_estimators=300, learning_rate=0.05, max_depth=5,
                          random_state=42, verbosity=0)
        xm.fit(X_tr_f, y_tr_f2)
        xp = xm.predict(X_te_f)[:len(y_te_f)]
        roll_results['XGBoost'].append(mean_absolute_error(y_te_f, xp))
    except Exception as e:
        print(f"  XGBoost {fold_name} failed: {e}")

    print(f"  {fold_name}: train={train_end_idx}d, test={len(y_te_f)}d")

# Summary table
print(f"\n  {'Model':12s} {'Fold1 MAE':>12s} {'Fold2 MAE':>12s} {'Fold3 MAE':>12s} {'Avg MAE':>12s}")
print(f"  {'─'*55}")
roll_avg = {}
for model_name, maes in roll_results.items():
    if len(maes) == 0:
        continue
    avg = np.mean(maes)
    roll_avg[model_name] = avg
    vals = [f'{m:>12,.0f}' for m in maes]
    while len(vals) < 3: vals.append(f"{'N/A':>12s}")
    print(f"  {model_name:12s} {'  '.join(vals)} {avg:>12,.0f}")

best_roll = min(roll_avg, key=roll_avg.get) if roll_avg else 'N/A'
print(f"\n  Best model (avg MAE across folds): {best_roll}")
print(f"\n  ⚠️  MAPE note: MAPE values from the single split ({sarima_mape:.0f}%, "
      f"{prophet_mape:.0f}%, {xgb_mape:.0f}%) are inflated by near-zero denominator days.")
print(f"  ✅ Use MAE as the primary metric: avg daily revenue = "
      f"{daily_sales['y'].mean():,.0f} DZD, SARIMA MAE = {sarima_mae:,.0f} DZD "
      f"({sarima_mae/daily_sales['y'].mean()*100:.1f}% relative error).")

# Visualise rolling MAE
if roll_avg:
    fold_names   = [f[0] for f in folds[:3]]
    fig_roll, ax_roll = plt.subplots(figsize=(11, 5))
    fig_roll.suptitle("Additional Evaluation — 3-Fold Rolling-Window Backtest MAE",
                      fontsize=13, fontweight="bold")

    x_pos = np.arange(len(fold_names))
