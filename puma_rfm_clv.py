"""---
## Section 6 — Customer Lifetime Value (CLV) Prediction

### Methodology (following the reference guide)

```
Transactions
    │
    ├── BG/NBD Model ──────► Expected NUMBER of future transactions per customer
    │        │
    │        └── Diagnostic plots:
    │              • Frequency/Recency matrix
    │              • Probability-Alive matrix
    │              • Period-transactions model fit
    │              • Top 10 customers by predicted transactions (next 10 days)
    │              • Calibration vs Holdout validation
    │
    ├── Gamma-Gamma Model ─► Expected REVENUE per transaction per customer
    │        │
    │        └── Requires: frequency ≥ 1 (returning customers only)
    │              • Checks monetary ⊥ frequency (independence assumption)
    │              • Estimates conditional expected average profit
    │
    └── CLV = E[transactions] × E[revenue/transaction] × time horizon
               discounted to present value
```

**Target variable:** `CLV` — predicted total revenue from each customer
over the next **12 months**, discounted at 1% monthly rate.

**Key variables in the lifetimes summary table:**
| Column | Meaning |
|--------|---------|
| `frequency` | Number of **repeat** purchases (first excluded) |
| `recency` | Days between first and last purchase |
| `T` | Days between first purchase and observation end |
| `monetary_value` | Average transaction value across repeat purchases |

"""

