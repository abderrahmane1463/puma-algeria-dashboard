rfm['KMeans_Segment'] = rfm['KMeans_Cluster'].map(cluster_labels_map)

print("\nK-Means Segment Distribution:")
print(rfm['KMeans_Segment'].value_counts())
# ─────────────────────────────────────────────────────────────
# ADDITIONAL EVALUATION 1: DAVIES-BOULDIN INDEX
# ─────────────────────────────────────────────────────────────
# Davies-Bouldin (DB) measures the average similarity between
# each cluster and its most similar neighbour.
# DB = 0  → perfect separation (lower is better, unlike Silhouette)
# DB < 1  → well-separated clusters
# Provides a second independent validation alongside Silhouette.
# ─────────────────────────────────────────────────────────────

db_scores = {}
for k in range(2, 10):
    km_tmp = KMeans(n_clusters=k, random_state=42, n_init=10)
    lbl    = km_tmp.fit_predict(rfm_normal)
    db_scores[k] = davies_bouldin_score(rfm_normal, lbl)

db_k4 = db_scores[OPTIMAL_K]
db_k2 = db_scores[2]

print("\n── Davies-Bouldin Index (lower = better separation) ─────────────")
print(f"  {'k':>4s} | {'DB Index':>10s} | {'Silhouette':>12s}")
print(f"  {'─'*32}")
for k in range(2, 10):
    flag = ' ← chosen' if k == OPTIMAL_K else (' ← stat. best sil.' if k == best_k_sil else '')
    print(f"  {k:>4d} | {db_scores[k]:>10.4f} | {silhouette_list[k-2]:>12.4f}{flag}")

print(f"\n  Summary for k=4 (chosen):")
print(f"    Silhouette  : {silhouette_list[OPTIMAL_K-2]:.4f}  (higher = better, max=1)")
print(f"    Davies-Bouldin : {db_k4:.4f}  (lower = better, min=0)")
print(f"    Both metrics confirm k=4 yields acceptable, CRM-actionable separation.")

# Plot DB curve
fig_db, axes_db = plt.subplots(1, 2, figsize=(14, 5))
fig_db.suptitle("Additional Evaluation — Davies-Bouldin Index vs Silhouette",
                fontsize=13, fontweight="bold")

