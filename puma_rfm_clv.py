# STEP 4: FIT FINAL K-MEANS (k=4)
# ─────────────────────────────────────────────────────────────

OPTIMAL_K = 4

km_final             = KMeans(n_clusters=OPTIMAL_K, random_state=42, n_init=10)
rfm['KMeans_Cluster'] = km_final.fit_predict(rfm_normal)

