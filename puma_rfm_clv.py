# ─────────────────────────────────────────────────────────────
# SECTION 3B: RFM — K-MEANS CLUSTERING (Data-Driven Segmentation)
# ─────────────────────────────────────────────────────────────
# Complements the rule-based RFM segments above with
# unsupervised K-Means clustering for statistical rigor.
#
# Pipeline:
#   1. Selective log1p transform (Frequency & Monetary only)
#      Recency skewness = 0.23 → already normal → no transform
#   2. StandardScaler normalization
#   3. Elbow + Silhouette to find optimal k
#   4. K-Means clustering (k=4, elbow-justified)
#   5. Snake plot + Relative importance heatmap + t-SNE + profiles
# ─────────────────────────────────────────────────────────────

from sklearn.preprocessing import StandardScaler
from sklearn.cluster import KMeans
from sklearn.metrics import silhouette_score
from sklearn.manifold import TSNE
from scipy import stats

print("\n📐 Section 3B — RFM K-Means Clustering")

# ─────────────────────────────────────────────────────────────
# SEGMENT COLOR PALETTE — fixed per segment name
# Used consistently across ALL plots in this section
# ─────────────────────────────────────────────────────────────

SEGMENT_COLORS = {
    'Champions' : '#2ecc71',   # green  — best customers
    'At Risk'   : '#e67e22',   # orange — were good, fading
    'Promising' : '#3498db',   # blue   — new/low engagement
    'Dormant'   : '#e74c3c',   # red    — lost/inactive
}

# ─────────────────────────────────────────────────────────────
# STEP 1: SELECTIVE TRANSFORM
# Recency  → skewness 0.23  → already normal → NO transform
# Frequency → skewness 8.00 → highly skewed  → log1p
# Monetary  → skewness 6.41 → highly skewed  → log1p
# ─────────────────────────────────────────────────────────────

rfm_log = rfm[['Recency', 'Frequency', 'Monetary']].copy()

# Safety shift for Monetary (handles zeros/negatives from returns)
if rfm_log['Monetary'].min() <= 0:
    rfm_log['Monetary'] = (rfm_log['Monetary'] - rfm_log['Monetary'].min()) + 1

# Apply log1p ONLY to skewed columns — Recency left untouched
rfm_log['Frequency'] = np.log1p(rfm_log['Frequency'])
rfm_log['Monetary']  = np.log1p(rfm_log['Monetary'])

print("\nSkewness BEFORE transform:")
print(rfm[['Recency', 'Frequency', 'Monetary']].skew().round(3))

print("\nSkewness AFTER selective log1p transform:")
print(rfm_log.skew().round(3))

# ─────────────────────────────────────────────────────────────
# STEP 2: STANDARDIZE (mean=0, std=1)
# Ensures R, F, M contribute equally to K-Means distances
# ─────────────────────────────────────────────────────────────

scaler     = StandardScaler()
rfm_normal = scaler.fit_transform(rfm_log)
rfm_normal = pd.DataFrame(
    rfm_normal,
    index=rfm_log.index,
    columns=rfm_log.columns
)

print("\nAfter StandardScaler — mean ≈ 0, std ≈ 1:")
print(rfm_normal.describe().round(3))

# ─────────────────────────────────────────────────────────────
# STEP 3: FIND OPTIMAL K — ELBOW + SILHOUETTE
# ─────────────────────────────────────────────────────────────

n_clusters_range = range(2, 10)
inertia_list     = []
silhouette_list  = []

print("\nSearching optimal k...")

for k in n_clusters_range:
    km     = KMeans(n_clusters=k, random_state=42, n_init=10)
    labels = km.fit_predict(rfm_normal)
    inertia_list.append(km.inertia_)
    silhouette_list.append(silhouette_score(rfm_normal, labels))
    print(f"  k={k} | Inertia: {km.inertia_:,.1f} | Silhouette: {silhouette_list[-1]:.4f}")

# Auto-detect elbow via second derivative
inertia_diffs  = np.diff(inertia_list)
inertia_diffs2 = np.diff(inertia_diffs)
best_k_elbow   = list(n_clusters_range)[1:][np.argmax(inertia_diffs2) + 1]
best_k_sil     = list(n_clusters_range)[silhouette_list.index(max(silhouette_list))]

print(f"\n  → Best k by Elbow      : {best_k_elbow}")
print(f"  → Best k by Silhouette : {best_k_sil}")
print(f"  → Selected k=4 (elbow-justified, CRM-actionable)")

# Plot
fig, axes = plt.subplots(1, 2, figsize=(14, 5))
fig.suptitle("Step 3 — Optimal Number of Clusters (k)", fontsize=13, fontweight="bold")

k_list = list(n_clusters_range)

axes[0].plot(k_list, inertia_list, marker='o', color='steelblue', linewidth=2, markersize=8)
axes[0].axvline(best_k_elbow, color='red', linestyle='--', linewidth=1.5,
                label=f'Elbow at k={best_k_elbow}')
axes[0].set_title("Elbow Curve — Within-Cluster SSE", fontweight="bold")
axes[0].set_xlabel("Number of Clusters (k)")
axes[0].set_ylabel("Inertia")
axes[0].legend()
axes[0].annotate(
    f'Elbow k={best_k_elbow}',
    xy=(best_k_elbow, inertia_list[best_k_elbow - 2]),
    xytext=(best_k_elbow + 0.5, inertia_list[best_k_elbow - 2] * 1.05),
    arrowprops=dict(arrowstyle='->', color='red'),
    fontsize=10, color='red'
)

axes[1].plot(k_list, silhouette_list, marker='o', color='darkorange', linewidth=2, markersize=8)
axes[1].axvline(best_k_sil, color='green', linestyle='--', linewidth=1.5,
                label=f'Best Silhouette at k={best_k_sil}')
axes[1].set_title("Silhouette Score by k", fontweight="bold")
axes[1].set_xlabel("Number of Clusters (k)")
axes[1].set_ylabel("Silhouette Score")
axes[1].legend()
axes[1].annotate(
    f'Best k={best_k_sil}\nScore={max(silhouette_list):.3f}',
    xy=(best_k_sil, max(silhouette_list)),
    xytext=(best_k_sil + 0.4, max(silhouette_list) - 0.02),
    arrowprops=dict(arrowstyle='->', color='green'),
    fontsize=10, color='green'
)

plt.tight_layout()
plt.savefig("fig_10_elbow_silhouette.png", dpi=150, bbox_inches='tight')
plt.show()
print("✅ Fig 10: Elbow + Silhouette")

