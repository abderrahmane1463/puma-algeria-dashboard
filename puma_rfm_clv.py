def rstr(df, pred=None):
    obs = df.shape[0]
    types = df.dtypes
    counts = df.apply(lambda x: x.count())
    uniques = df.apply(lambda x: str(x.unique())) # Corrected: Convert unique array to string
    nulls = df.apply(lambda x: x.isnull().sum())
    distincts = df.apply(lambda x: x.unique().shape[0])
    missing_ration = (df.isnull().sum()/ obs) * 100

    # Calculate skewness and kurtosis only for numerical columns
    numeric_df = df.select_dtypes(include=['number'])
    skewness = numeric_df.skew()
    kurtosis = numeric_df.kurt()

    print('Data shape:', df.shape)

    if pred is None:
        # Ensure skewness and kurtosis are aligned with all columns, filling NaN for non-numeric
        all_skewness = pd.Series(index=df.columns, dtype=float).fillna(0) # Initialize with zeros/NaN
        all_skewness.update(skewness)
        all_kurtosis = pd.Series(index=df.columns, dtype=float).fillna(0) # Initialize with zeros/NaN
        all_kurtosis.update(kurtosis)

        cols = ['types', 'counts', 'distincts', 'nulls', 'missing ration', 'uniques', 'skewness', 'kurtosis']
        str_df = pd.concat([types, counts, distincts, nulls, missing_ration, uniques, all_skewness, all_kurtosis], axis = 1) # Removed sort=True

    else:
        corr = numeric_df.corr()[pred] # Correlation also needs numeric data
        all_skewness = pd.Series(index=df.columns, dtype=float).fillna(0)
        all_skewness.update(skewness)
        all_kurtosis = pd.Series(index=df.columns, dtype=float).fillna(0)
        all_kurtosis.update(kurtosis)

        str_df = pd.concat([types, counts, distincts, nulls, missing_ration, uniques, all_skewness, all_kurtosis, corr], axis = 1) # Removed sort=True
        corr_col = 'corr '  + pred
        cols = ['types', 'counts', 'distincts', 'nulls', 'missing ration', 'uniques', 'skewness', 'kurtosis', corr_col ]

    str_df.columns = cols
    dtypes = str_df.types.value_counts()
    print('___________________________')
    print('Data types:\n',str_df.types.value_counts())
    print('___________________________')
    return str_df

