axes_db[0].plot(k_list_db, db_vals, marker='o', color='#9b59b6', linewidth=2, markersize=8)
axes_db[0].axvline(OPTIMAL_K, color='red', linestyle='--', linewidth=1.5,
                   label=f'Chosen k={OPTIMAL_K}')
