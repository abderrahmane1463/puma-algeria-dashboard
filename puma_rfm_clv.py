# EXPLANATION:
# Before any analysis we must:
#  - Drop irrelevant or redundant columns
#  - Parse dates and extract time-based features (hour, day, month)
#  - Clean the monetary column (Total TTC ligne) which arrives as string
#  - Flag return transactions (negative quantity = customer return)
#  - Classify clients into business-meaningful types
#  - Impute missing categorical values using article-level context

print("\n🔧 Step 1 — Data Cleaning & Feature Engineering")

# 1.1 Drop columns not needed for analysis
columns_to_drop = [
    'Date création doc.',       # Duplicate temporal info (Heure de création is richer)
    'Etablissement du doc.',    # Internal doc reference, not analytical
    'Désignation ligne',        # Long text, same info as Libellé article
    'Unnamed: 18',              # Empty trailing column
    'Prix unitaire TTC net ligne'  # We keep Total TTC; unit price is derivable
]
puma.drop(columns=columns_to_drop, inplace=True)

# 1.2 Parse datetime and extract time features
puma['Heure de création'] = pd.to_datetime(puma['Heure de création'])
puma['Date_Only']   = puma['Heure de création'].dt.date
puma['Year']        = puma['Heure de création'].dt.year
puma['Month']       = puma['Heure de création'].dt.month
puma['Week']        = puma['Heure de création'].dt.isocalendar().week.astype(int)
puma['Hour_of_Day'] = puma['Heure de création'].dt.hour
puma['Day_Name']    = puma['Heure de création'].dt.day_name()
puma['Month_Name']  = puma['Heure de création'].dt.strftime('%B')

# 1.3 Clean the monetary column (stored as "11 950" string in French format)
def clean_currency(value):
    if isinstance(value, str):
        clean_val = "".join(filter(lambda x: x.isdigit() or x in ".-", value))
        return clean_val if clean_val not in ("", "-", ".") else np.nan
    return value

puma['Total TTC ligne'] = pd.to_numeric(
    puma['Total TTC ligne'].apply(clean_currency), errors='coerce'
)

# 1.4 Flag return transactions (returns have negative quantity)
puma['Is_Return'] = puma['Quantité'] < 0

# 1.5 Client type classification
# SC000004 = anonymous walk-in cashier code
# P* = internal employee purchases
# AMB* = partner / CRB sports club
# All other unique IDs = loyalty card holders
def segment_client(client_id):
    c = str(client_id).strip().upper()
    if c == 'SC000004':
        return 'Walk-in'
    elif c.startswith('P'):
        return 'Employee'
    elif c.startswith('AMB'):
        return 'Partner (CRB)'
    else:
        return 'Loyal (Fidelity)'

puma['Client_Type'] = puma['Client'].apply(segment_client)

# 1.6 Impute missing product metadata using article code context
# If article X has a known category in most rows, propagate it to any missing rows
for col in ['Category ligne doc', 'Saison', 'Category Age ligne doc']:
    puma[col] = puma.groupby('Code article')[col].transform(
        lambda x: x.ffill().bfill()
    )

# 1.7 Fill zero-total rows with "Unknown" label
target_cols = ['Category ligne doc', 'Category Age ligne doc', 'Saison', 'LIBDIM1']
puma.loc[puma['Total TTC ligne'] == 0, target_cols] = "Unknown"

