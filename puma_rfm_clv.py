# Build rule-based segments for colour coding (same as reference
# which colours by RFM_Loyalty_Level)
def rfm_segment(row):
    r = row['R_Score_tmp']; f = row['F_Score_tmp'] # Changed from R_Score, F_Score to R_Score_tmp, F_Score_tmp
    if r >= 4 and f >= 4:   return 'Champions'
    elif f >= 4:             return 'Loyal Customers'
    elif r >= 4 and f <= 2:  return 'New Customers'
    elif r <= 2 and f >= 3:  return 'At Risk'
    else:                    return 'Lost'

